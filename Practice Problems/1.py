# Fair coin tossed 100 times

total_tosses = 100

heads = 50
tails = 50

probability_head = heads / total_tosses
probability_tail = tails / total_tosses

print("Number of heads:", heads)
print("Number of tails:", tails)
print("Experimental probability of Head:", probability_head)
print("Experimental probability of Tail:", probability_tail)
